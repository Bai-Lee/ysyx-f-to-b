"""Narrow, fail-closed structural export of the actual F tutorial .circ.

This is a native XML/net-graph translator, NOT Logisim's GUI HDL exporter.
Only single-bit east-facing NOT and 2-input AND/OR gates are supported.
Interior/interior crossing is not a junction; endpoints and gate pins are.
"""
from common import *
from run import BIN
import xml.etree.ElementTree as ET
from datetime import datetime,timezone


def coordinate(text):
    match=re.fullmatch(r'\((-?\d+),(-?\d+)\)',text)
    if not match:raise ValueError('Invalid coordinate '+str(text))
    return tuple(map(int,match.groups()))


def on_segment(p,a,b):
    return ((a[0]==b[0]==p[0] and min(a[1],b[1])<=p[1]<=max(a[1],b[1])) or
            (a[1]==b[1]==p[1] and min(a[0],b[0])<=p[0]<=max(a[0],b[0])))


def net_graph(wires,pins):
    points=set(pins)
    for a,b in wires:
        if not (a[0]==b[0] or a[1]==b[1]):raise ValueError('Diagonal wire unsupported')
        points.update((a,b))
    parent={p:p for p in points}
    def find(p):
        while parent[p]!=p:parent[p]=parent[parent[p]];p=parent[p]
        return p
    for a,b in wires:
        for p in points:
            if on_segment(p,a,b):parent[find(p)]=find(a)
    groups={}
    for p in sorted(points):groups.setdefault(find(p),[]).append(p)
    nets=sorted(groups.values(),key=lambda g:min(g))
    return {p:'n'+str(i) for i,g in enumerate(nets) for p in g},nets


def translate(source,target):
    root=ET.parse(source).getroot();main=root.find('main').attrib['name']
    circuits=[c for c in root.findall('circuit') if c.get('name')==main]
    if len(circuits)!=1:raise ValueError('Ambiguous/missing main')
    circuit=circuits[0];wires=[(coordinate(w.get('from')),coordinate(w.get('to'))) for w in circuit.findall('wire')]
    parts=[];allpins=[];names=set()
    for index,c in enumerate(circuit.findall('comp')):
        name=c.get('name');loc=coordinate(c.get('loc'));a={n.get('name'):n.get('val') for n in c.findall('a')}
        if name=='Pin':
            label=a['label'];direction=a.get('type','input')
            if not re.fullmatch(r'[A-Za-z_]\w*',label) or label in names:raise ValueError('Invalid/repeated pin label')
            if direction not in ('input','output') or a.get('width','1')!='1':raise ValueError('Unsupported pin')
            names.add(label);part={'name':name,'label':label,'direction':direction,'ports':[loc],'loc':loc,'index':index}
        elif name in ('NOT Gate','AND Gate','OR Gate'):
            if a.get('facing','east')!='east' or a.get('width','1')!='1':raise ValueError('Unsupported gate orientation/width')
            if name=='NOT Gate':
                if a.get('size','30')!='30':raise ValueError('Unsupported NOT size')
                ports=[loc,(loc[0]-30,loc[1])]
            else:
                if a.get('inputs','5')!='2' or a.get('size','50')!='50':raise ValueError('Unsupported multi-input gate geometry')
                ports=[loc,(loc[0]-50,loc[1]-20),(loc[0]-50,loc[1]+20)]
            if set(a)-{'facing','width','inputs','size','label'}:raise ValueError('Unsupported gate attributes')
            part={'name':name,'primitive':{'NOT Gate':'not','AND Gate':'and','OR Gate':'or'}[name],'ports':ports,'loc':loc,'index':index}
        else:raise ValueError('Unsupported component '+str(name))
        parts.append(part);allpins.extend(part['ports'])
    lookup,nets=net_graph(wires,allpins);drivers={n:[] for n in lookup.values()};consumers={n:[] for n in lookup.values()}
    for p in parts:
        p['nets']=[lookup[loc] for loc in p['ports']]
        if p['name']=='Pin':
            (drivers if p['direction']=='input' else consumers)[p['nets'][0]].append(p['label'])
        else:
            drivers[p['nets'][0]].append('gate_'+str(p['index']))
            for n in p['nets'][1:]:consumers[n].append('gate_'+str(p['index']))
    for n in drivers:
        if len(drivers[n])!=1:raise ValueError(f'{n}: expected exactly one driver, got {drivers[n]}')
        if not consumers[n]:raise ValueError(f'{n}: disconnected/unconsumed net')
    # Topological order must exist: this tutorial is pure combinational logic.
    known={p['nets'][0] for p in parts if p['name']=='Pin' and p['direction']=='input'}
    pending=[p for p in parts if p['name']!='Pin']
    while pending:
        ready=[p for p in pending if set(p['nets'][1:])<=known]
        if not ready:raise ValueError('Combinational cycle/unreachable driver')
        for p in ready:known.add(p['nets'][0]);pending.remove(p)
    ports=[p['direction']+' wire '+p['label'] for p in parts if p['name']=='Pin']
    lines=['// Native net-graph export of '+source.name,'// Not generated by Logisim GUI; source is preserved unchanged.','`default_nettype none','module xor_from_circ('+', '.join(ports)+');','wire '+','.join('n'+str(i) for i in range(len(nets)))+';']
    for p in parts:
        if p['name']=='Pin':lines.append('assign '+(p['nets'][0]+'='+p['label'] if p['direction']=='input' else p['label']+'='+p['nets'][0])+';')
        else:lines.append(f'{p["primitive"]} gate_{p["index"]}({",".join(p["nets"])}); // {p["name"]} at {p["loc"]}')
    lines+=['endmodule','`default_nettype wire'];target.write_text('\n'.join(lines)+'\n',encoding='utf8')
    return {'source':str(source),'source_sha256':sha(source),'export':str(target),'export_sha256':sha(target),'parts':parts,'nets':[{'name':'n'+str(i),'points':g,'drivers':drivers['n'+str(i)],'consumers':consumers['n'+str(i)]} for i,g in enumerate(nets)]}


def main():
    source=ROOT/'F/circuits/tutorial_reference_complete.circ';folder=OUT/'export';folder.mkdir(exist_ok=True)
    target=folder/'tutorial_export.v';record=translate(source,target)
    # Check parser's crossing rule independently of the tutorial circuit.
    crossing=[((0,10),(20,10)),((10,0),(10,20))]
    isolated,_=net_graph(crossing,[]);assert isolated[(0,10)]!=isolated[(10,0)]
    joined,_=net_graph(crossing,[(10,10)]);assert joined[(0,10)]==joined[(10,0)]
    bad=ET.parse(source);c=bad.getroot().find('circuit');wire=next(w for w in c.findall('wire') if w.get('from')=='(550,200)' and w.get('to')=='(650,200)');c.remove(wire)
    badpath=ROOT/'artifacts/E1/export/disconnected_output/input.circ';badpath.parent.mkdir(parents=True,exist_ok=True);bad.write(badpath,encoding='utf-8',xml_declaration=True)
    try:translate(badpath,ROOT/'temp/E1/tutorial_bad_export.v')
    except ValueError as e:record['disconnected_output_control']={'status':'PASS','error':str(e),'input':str(badpath),'input_sha256':sha(badpath)}
    else:raise AssertionError('Disconnected output was accepted')
    tb=folder/'tutorial_export_tb.sv'
    tb.write_text('''`timescale 1ns/1ps
module tb;reg X,Y;wire Z;integer i;xor_from_circ dut(X,Y,Z);
initial begin
for(i=0;i<4;i=i+1)begin {X,Y}=i;#1;if(Z!==(X!=Y))$fatal(1,"MISMATCH tutorial_export row=%0d got=%b",i,Z);end
$display("PASS tutorial_export checks=4");$finish;end endmodule
''',encoding='utf8')
    runs=[]
    for suffix,dut,expected in [('normal',target,0),('or_changed_to_and',ROOT/'temp/E1/tutorial_mutated.v',1)]:
        if expected:
            text=target.read_text('utf8');assert text.count('or gate_')==1
            dut.write_text(text.replace('or gate_','and gate_'),encoding='utf8')
        binary=ROOT/'temp/E1'/('tutorial_'+suffix+'.vvp')
        compile_=run('E1/export/'+suffix+'/compile',[BIN/'iverilog.exe','-g2012','-s','tb','-o',binary,dut,tb],[source,dut,tb],timeout=30)
        if compile_['status']!='PASS':raise RuntimeError('Export compile failed')
        sim=run('E1/export/'+suffix+'/simulate',[BIN/'vvp.exe',binary],[source,dut,tb,binary],expected=expected,timeout=30)
        out=(ROOT/'artifacts/E1/export'/suffix/'simulate/stdout.log').read_text('utf8')
        assert sim['status']=='PASS' and ('MISMATCH' if expected else 'PASS tutorial_export checks=4') in out
        runs.append({'name':suffix,'status':'PASS','compile':compile_,'simulation':sim})
    record.update(status='PASS_ADAPTED',crossing_tests='PASS: interior/interior separate; explicit endpoint/pin joins',runs=runs,timestamp=datetime.now(timezone.utc).isoformat(),source_unchanged=sha(source)==record['source_sha256'],adaptation='User authorized command-line alternatives; native XML connectivity export replaces Logisim GUI HDL generation. Not an official Logisim exporter claim.')
    dump(folder/'connectivity.json',record);dump(ROOT/'reports/E1_export.json',record)
    print('E1_EXPORT PASS_ADAPTED',len(record['parts']),'components',len(record['nets']),'nets',flush=True)


if __name__=='__main__':main()
