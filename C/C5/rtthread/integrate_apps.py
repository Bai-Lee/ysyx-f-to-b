from pathlib import Path
import sys,argparse,re
sys.path.insert(0,str(Path(__file__).resolve().parents[2]/'runtime'))
sys.path.insert(0,str(Path(__file__).resolve().parents[1]))
from common import *
from build_app import compile_app


def main():
    parser=argparse.ArgumentParser();parser.add_argument('--memory',choices=['sdram32','sdram64','sdram128'],default='sdram128');args=parser.parse_args()
    arch='riscv32e-ysyxsoc-'+args.memory;base=WORK/'c5/workbench';am=base/'abstract-machine';bsp=WORK/'c5/rt-thread-interactive/bsp/abstract-machine'
    shutil.copyfile(ROOT/'C/C5/rtthread/acceptance.c',bsp/'src/acceptance.c')
    jobs=json.loads((ROOT/'reports/C5_app_setup.json').read_text())['jobs']
    integrated=[];make_lines=['# Generated by C5/rtthread/integrate_apps.py; only checked subprocesses and -j1.','SRCS += build/c5-am-apps.c'];wrappers=[]
    for key,name,argument in [('hello','hello',''),('microbench','microbench','test'),('typing-game','typing_game',''),('snake','snake',''),('fceux','fceux','interaction')]:
        built=compile_app(key,args.memory,argument);source=Path(jobs[key]['destination'])/'build'/arch;objects=sorted(source.rglob('*.o'));assert objects,(key,source)
        libs=[];defined=set()
        for library in ['am','klib']:
            archive=am/library/'build'/(library+'-'+arch+'.a');libs.append(archive)
            output,_,_=run('C5/rtthread/integration/'+name+'/symbols-'+library,['riscv64-linux-gnu-nm','-g','--defined-only','--format=just-symbols',archive],inputs=[archive])
            defined|={line for line in output.splitlines() if re.fullmatch(r'[A-Za-z_.$][A-Za-z0-9_.$]*',line)}
        destination=bsp/'build'/arch/'am-apps'/name;destination.mkdir(parents=True,exist_ok=True)
        transform_log=ROOT/'artifacts/C5/rtthread/integration'/name/'transforms.json'
        if transform_log.exists():
            attempt=transform_log.parent/'attempts'/str(time.time_ns());attempt.mkdir(parents=True)
            shutil.copyfile(transform_log,attempt/'transforms.json')
            with zipfile.ZipFile(attempt/'derived_objects.zip','w',zipfile.ZIP_DEFLATED) as archive:
                for item in sorted(destination.glob('*')):
                    if item.is_file():archive.write(item,item.name)
        prefix='__am_'+name+'_';mapping=destination/'redefine.txt';renames=[]
        for symbol in sorted(defined|{'halt','exit'}):
            target='c5_dummy_'+symbol if symbol in ['ioe_init','cte_init','vme_init','mpe_init'] else 'c5_am_'+symbol if symbol in ['halt','exit'] else symbol
            renames.append(prefix+symbol+' '+target)
        mapping.write_text('\n'.join(renames)+'\n')
        commands=[];outputs=[];tool=Path(shutil.which('riscv64-linux-gnu-objcopy'))
        def transform(command):
            start=time.monotonic();result=subprocess.run(command,capture_output=True,text=True)
            commands.append({'command':command,'cwd':str(Path.cwd()),'exit_code':result.returncode,'stdout':result.stdout,'stderr':result.stderr,'elapsed_seconds':time.monotonic()-start})
            dump(transform_log,{'status':'FAIL' if result.returncode else 'IN_PROGRESS','tool':str(tool),'tool_sha256':sha(tool),'commands':commands})
            result.check_returncode()
        for number,original in enumerate(objects):
            target=destination/(f'{number:04d}_'+original.name);shutil.copyfile(original,target)
            command=[str(tool),'--prefix-symbols='+prefix,'--prefix-alloc-sections=__am_apps',str(target)]
            transform(command)
            command=[str(tool),'--redefine-syms='+str(mapping),str(target)]
            transform(command)
            make_lines.append('SRCS += '+str(target.relative_to(bsp/'build'/arch)))
            outputs.append({'path':str(target),'sha256':sha(target),'source':str(original),'source_sha256':sha(original)})
        if name=='microbench':
            allocator_source=Path(jobs[key]['destination'])/'src/bench.c';allocator_text=allocator_source.read_text()
            assert 'hbrk = (void *)ROUNDUP(heap.start, 8);' in allocator_text and 'void* bench_alloc(size_t size)' in allocator_text
            allocator={'kind':'private arena','source':str(allocator_source),'sha256':sha(allocator_source),'reason':'Originalbench_reset/bench_alloc ownheapstorage directly; klib metadata is not its contract.'}
        else:allocator={'kind':'klib','reason':'Sharedklib allocation API ornoheapallocation; metadata validation applies.'}
        wrappers.append(f'extern int {prefix}main(const char *);\nstatic void am_{name}(int argc,char **argv){{app_start("{name}",{prefix}main,argc,argv,{"false" if name=="microbench" else "true"});}}\nMSH_CMD_EXPORT(am_{name},AM {name});\n')
        dump(transform_log,{'status':'PASS','tool':str(tool),'tool_sha256':sha(tool),'commands':commands,'outputs':outputs})
        integrated.append({'name':name,'allocator':allocator,'source_build':built,'original_objects':len(objects),'outputs':outputs,'commands':commands,'mapping_sha256':sha(mapping)})
    runtime=(ROOT/'C/C5/rtthread/app_runtime.c.in').read_text().replace('/* APP_WRAPPERS */','\n'.join(wrappers));generated=bsp/'build/c5-am-apps.c';generated.write_text(runtime)
    makefile=bsp/'build'/arch/'am-apps.mk';makefile.write_text('\n'.join(make_lines)+'\n')
    image=bsp/'build'/('rtthread-'+arch+'.bin');elf=image.with_suffix('.elf')
    source=[generated,makefile,ROOT/'C/C5/rtthread/app_runtime.c.in',*sorted((bsp/'src').glob('*.c')),bsp/'files.mk',bsp/'rtconfig.h',am/'scripts'/('ysyxsoc-code-'+args.memory+'.ld')]
    source += [Path(row['path']) for app in integrated for row in app['outputs']]
    tag='C5/rtthread/integration/'+args.memory
    run(tag+'/link',['make','-j1','ARCH='+arch,'insert-arg'],cwd=bsp,env={'AM_HOME':str(am)},inputs=source,outputs=[image,elf],timeout=600)
    assert image.stat().st_size<=16*1024**2
    text,_,_=run(tag+'/final-symbols',['riscv64-linux-gnu-nm','-n',elf],inputs=[elf]);symbols={v[2]:int(v[0],16) for line in text.splitlines() if len(v:=line.split())==3 and re.fullmatch('[0-9a-fA-F]+',v[0])}
    for app in integrated:assert 0xa0000000<=symbols['__am_'+app['name']+'_main']<0xa8000000
    assert symbols['__am_apps_data_end']>symbols['__am_apps_data_start'] and symbols['__am_apps_bss_end']>symbols['__am_apps_bss_start']
    dump(ROOT/('reports/C5_rtthread_apps_'+args.memory+'.json'),{'status':'BUILT_NOT_RUNTIME_ACCEPTED','memory':args.memory,'image':str(image),'elf':str(elf),'image_sha256':sha(image),'elf_sha256':sha(elf),'image_bytes':image.stat().st_size,'applications':integrated,'symbols':symbols,'evidence':'artifacts/'+tag,'scope':'NJU RT-Thread and selected realAM applications, namespaced objects and grouped initialized/zero data. Heap-owned startup arguments, per-launch app-data restore and klib_heap_reset, captured exitcodes, realthread exit backtoshell. All compilation uses-j1 and checked subprocess exits. GUI operation/return behavior not yet accepted.'})
    print('C5_RTTHREAD_AM_APPS_BUILT',args.memory,image.stat().st_size,flush=True)


if __name__=='__main__':main()
